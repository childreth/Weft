// Regenerates src/font-catalog.ts from Google Fonts' public metadata (no API key):
//   node packages/core/scripts/build-font-catalog.mjs [metadata.json]
// Without a file argument it downloads https://fonts.google.com/metadata/fonts.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CATEGORIES = { 'Sans Serif': 's', Serif: 'r', Display: 'd', Handwriting: 'h', Monospace: 'm' };

const raw = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch('https://fonts.google.com/metadata/fonts')).text();
const { familyMetadataList } = JSON.parse(raw.slice(raw.indexOf('{')));

const rows = familyMetadataList
  .filter((f) => f.isOpenSource !== false && !f.isBrandFont && CATEGORIES[f.category])
  .sort((a, b) => a.popularity - b.popularity)
  .map((f) => {
    const styles = Object.keys(f.fonts);
    const weights = [...new Set(styles.map((s) => Number.parseInt(s, 10)))].filter(Number.isFinite).sort((a, b) => a - b);
    const italic = styles.some((s) => s.endsWith('i'));
    // [family, category, weights, italic?]
    return [f.family, CATEGORIES[f.category], weights, italic ? 1 : 0];
  });

const out = `// Generated by scripts/build-font-catalog.mjs from Google Fonts metadata (${new Date().toISOString().slice(0, 10)}). Do not edit.
// [family, category (s sans, r serif, d display, h handwriting, m mono), weights, italic], most popular first.
export const FONT_CATALOG_ROWS: ReadonlyArray<readonly [string, string, readonly number[], number]> = ${JSON.stringify(rows)};
`;
writeFileSync(join(import.meta.dirname, '../src/font-catalog.ts'), out);
console.log(`${rows.length} families, ${(out.length / 1024).toFixed(0)} KB`);
