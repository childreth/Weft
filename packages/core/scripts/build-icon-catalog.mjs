// Regenerates src/icon-catalog.ts: every Material Symbols icon name (from the font's codepoints
// file, so each name is a ligature the font really has), most popular first, with a few search
// tags from Google Fonts' icon metadata. No API key:
//   node packages/core/scripts/build-icon-catalog.mjs [codepoints-file] [metadata.json]
// Without arguments it downloads both. Icons are Apache 2.0 (google/material-design-icons).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CODEPOINTS =
  'https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL,GRAD,opsz,wght%5D.codepoints';
const METADATA = 'https://fonts.google.com/metadata/icons?incomplete=1&key=material_symbols';
const MAX_TAGS = 6;
/** Tags on more icons than this ("outline", "button") don't help tell icons apart. */
const MAX_TAG_USES = 120;

const text = async (file, url) => (file ? readFileSync(file, 'utf8') : await (await fetch(url)).text());
const codepoints = await text(process.argv[2], CODEPOINTS);
const metadata = await text(process.argv[3], METADATA);
const { icons } = JSON.parse(metadata.slice(metadata.indexOf('{')));

const meta = new Map();
for (const icon of icons) {
  const seen = meta.get(icon.name);
  if (!seen || icon.popularity > seen.popularity) meta.set(icon.name, icon);
}
const uses = new Map();
for (const icon of meta.values()) for (const t of new Set(icon.tags ?? [])) uses.set(t, (uses.get(t) ?? 0) + 1);
const names = [...new Set(codepoints.split('\n').map((l) => l.split(' ')[0]).filter(Boolean))];
const rows = names
  .map((name) => {
    const m = meta.get(name);
    const words = new Set(name.split('_'));
    const tags = (m?.tags ?? [])
      .filter((t) => /^[a-z]+$/.test(t) && !words.has(t) && uses.get(t) <= MAX_TAG_USES)
      .sort((a, b) => uses.get(a) - uses.get(b))
      .slice(0, MAX_TAGS);
    return { name, popularity: m?.popularity ?? 0, tags };
  })
  .sort((a, b) => b.popularity - a.popularity || a.name.localeCompare(b.name))
  .map(({ name, tags }) => (tags.length ? `${name} ${tags.join(',')}` : name));

const out = `// Generated by scripts/build-icon-catalog.mjs from Material Symbols (Apache 2.0) (${new Date().toISOString().slice(0, 10)}). Do not edit.
// "name tag,tag,tag" per icon, most popular first. Each name is a ligature in the Material Symbols fonts.
export const ICON_CATALOG_ROWS: readonly string[] = ${JSON.stringify(rows)};
`;
writeFileSync(join(import.meta.dirname, '../src/icon-catalog.ts'), out);
console.log(`${rows.length} icons, ${(out.length / 1024).toFixed(0)} KB`);
